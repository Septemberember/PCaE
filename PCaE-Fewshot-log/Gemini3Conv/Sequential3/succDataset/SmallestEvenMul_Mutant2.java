/**
 * Smallest Even Multiplication Utility.
 * This class contains a small demonstration method.
 * Note: The implementation in smallestEvenMultiple uses a compact conditional.
 */
 
public class SmallestEvenMul_Mutant2 {

    public static int smallestEvenMultiple(int n) {
        // This uses a concise parity check; returns n for even and also for odd here as a placeholder.
        return n % 2 == 0 ? n : 1 * n;
    }
}