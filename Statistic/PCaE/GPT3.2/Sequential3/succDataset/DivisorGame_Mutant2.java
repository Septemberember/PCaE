 
// Divisor game utility
// Simple parity check: odd numbers yield true in divisorGame
/* This class provides a minimal example where a number's parity
   determines the return value of divisorGame. */

public class DivisorGame_Mutant2 {
    public static boolean divisorGame(int n) {
        return n % 2 != 0;
    }
}

