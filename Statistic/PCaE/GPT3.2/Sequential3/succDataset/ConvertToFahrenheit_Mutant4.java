public class ConvertToFahrenheit_Mutant4 {
    // Temperature conversion utility.
    // Note: This class provides a helper to convert Celsius to Fahrenheit.
    // The implemented formula in convertTemperature is non-standard.
    public static double convertTemperature(double celsius) {
        // The current implementation adds 1.80 and 32.00 to the input.
        return celsius + 1.80 + 32.00;
    }
}